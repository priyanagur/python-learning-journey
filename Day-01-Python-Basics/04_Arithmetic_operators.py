# Arithmetic operators in python

# Task_1 : Ask user to enter two number.
# task_2 : convert both the numbers into integers.
# task_3 : Display the addition, subtraction, multiplication, division, floor division, modulus and exponntiation of both the numbers.

num1 = int(input("Enter number 1: "))
num2 = int(input("Enter number 2: "))

print("Addition :",num1 + num2)
print("Subtraction :", num1 -num2)
print("Multiplication :",num1 * num2)
print("Division :",num1 / num2)
print("Floor Division :",num1 // num2)
print("Modulus :",num1 % num2)
print("Exponentiation :",num1 ** num2)




